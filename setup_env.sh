#!/bin/bash
# setup_env.sh - Interactive setup for safeway-coupons environment variables
# This script prompts the user for required configuration and creates a .env file

echo "=== safeway-coupons Environment Setup ==="
echo ""

# Required variables
echo "Required environment variables for safeway-coupons:"
echo "----------------------------------------------------"
echo "These are used for authenticating to Safeway's 'Safeway for U' account."
echo ""

# Username
read -p "Enter your Safeway account email (username): " SAFEWAY_ACCOUNT_USERNAME
while [ -z "$SAFEWAY_ACCOUNT_USERNAME" ]; do
    echo "Username cannot be empty. Please try again."
    read -p "Enter your Safeway account email (username): " SAFEWAY_ACCOUNT_USERNAME
done

# Password
read -sp "Enter your Safeway account password: " SAFEWAY_ACCOUNT_PASSWORD
echo ""
while [ -z "$SAFEWAY_ACCOUNT_PASSWORD" ]; do
    echo "Password cannot be empty. Please try again."
    read -sp "Enter your Safeway account password: " SAFEWAY_ACCOUNT_PASSWORD
    echo ""
done

# Optional: email for notifications
read -p "Enter email address for coupon summary reports (or press Enter to skip): " SAFEWAY_ACCOUNT_MAIL_FROM
if [ -n "$SAFEWAY_ACCOUNT_MAIL_FROM" ]; then
    read -p "Enter email recipient address (default: same as username): " SAFEWAY_ACCOUNT_MAIL_TO
    if [ -z "$SAFEWAY_ACCOUNT_MAIL_TO" ]; then
        SAFEWAY_ACCOUNT_MAIL_TO="$SAFEWAY_ACCOUNT_USERNAME"
    fi
else
    SAFEWAY_ACCOUNT_MAIL_FROM=""
    SAFEWAY_ACCOUNT_MAIL_TO="$SAFEWAY_ACCOUNT_USERNAME"
fi

# Optional: cron schedule
read -p "Enter cron schedule (default: '*/5 * * * *' for every 5 minutes): " CRON_SCHEDULE
if [ -z "$CRON_SCHEDULE" ]; then
    CRON_SCHEDULE="*/5 * * * *"
fi

# Optional: time zone
read -p "Enter time zone (optional, e.g. 'America/Arizona'): " TZ

# Create .env file
echo ""
echo "=== Writing .env file ==="
cat > .env <<EOF
# Safeway Coupons Environment Configuration
# Generated by setup_env.sh

SAFEWAY_ACCOUNT_USERNAME="$SAFEWAY_ACCOUNT_USERNAME"
SAFEWAY_ACCOUNT_PASSWORD="$SAFEWAY_ACCOUNT_PASSWORD"
SAFEWAY_ACCOUNT_MAIL_FROM="$SAFEWAY_ACCOUNT_MAIL_FROM"
SAFEWAY_ACCOUNT_MAIL_TO="$SAFEWAY_ACCOUNT_MAIL_TO"
CRON_SCHEDULE="$CRON_SCHEDULE"
TZ="${TZ:-America/Arizona}"
EOF

echo ""
echo "✓ .env file created successfully!"
echo ""
echo "=== Configuration Summary ==="
echo "Username: $SAFEWAY_ACCOUNT_USERNAME"
echo "Mail From: $SAFEWAY_ACCOUNT_MAIL_FROM"
echo "Mail To: $SAFEWAY_ACCOUNT_MAIL_TO"
echo "Cron Schedule: $CRON_SCHEDULE"
echo "Time Zone: ${TZ:-America/Arizona}"
echo ""
echo "=== Next Steps ==="
echo "1. Review the .env file to ensure values are correct"
echo "2. Run safeway-coupons with: poetry run safeway-coupons"
echo "3. Or use Docker: docker-compose up -d"
echo ""
echo "⚠️  Security note: Keep .env file private and do not commit it to version control."